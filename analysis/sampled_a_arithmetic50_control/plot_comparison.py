import json,csv
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
root=Path(__file__).resolve().parents[1]
out=root/'qwen06b_sampled_a_arithmetic_50'
data=[json.load(open(root/name/'window_statistics.json')) for name in ['qwen06b_fixed_a_arithmetic_50','qwen06b_sampled_a_arithmetic_50']]
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':10,'text.color':'#172B4D','axes.labelcolor':'#526177','xtick.color':'#526177','ytick.color':'#526177','svg.fonttype':'none'})
fig,axes=plt.subplots(2,2,figsize=(12,8.4),sharey='row')
for col,(d,condition) in enumerate(zip(data,['Fixed A','Fresh A generated by each checkpoint'])):
 axes[0,col].set_title(condition,loc='left',fontsize=14,fontweight='bold',pad=18)
 for row,metric in enumerate(['plasticity','empowerment']):
  ax=axes[row,col]
  for window,label,color,style,marker in [('early_1_25','Tokens 1–25','#3568B0','-','o'),('later_26_50','Tokens 26–50','#D78132','--','s'),('full_1_50','Tokens 1–50','#25998D',':','D')]:
   r=sorted([x for x in d['means'] if x['metric']==metric and x['window']==window],key=lambda x:x['step'])
   xs=[x['step'] for x in r]
   ax.plot(xs,[x['mean'] for x in r],color=color,ls=style,marker=marker,lw=2.2,ms=5,label=label)
   ax.fill_between(xs,[x['low'] for x in r],[x['high'] for x in r],color=color,alpha=.07,linewidth=0)
  ax.axhline(0,color='#8E9DB0',ls=':',lw=1)
  ax.set_xticks([0,77,251]);ax.set_xlim(-20,271)
  ax.grid(axis='y',color='#E5EBF2');ax.set_axisbelow(True);ax.spines[['top','right']].set_visible(False)
  if col==0:ax.set_ylabel(('Plasticity: correction → B' if row==0 else 'Empowerment: A → B')+'\n(bits/token)')
  if row==1:ax.set_xlabel('Additional GRPO steps',labelpad=8)
  ax.tick_params(length=0,pad=5)
  ax.legend(frameon=False,fontsize=8,loc='upper right')
for row,metric in enumerate(['plasticity','empowerment']):
 r=[x for d in data for x in d['means'] if x['metric']==metric];lo=min(x['low'] for x in r);hi=max(0,max(x['high'] for x in r));gap=hi-lo
 axes[row,0].set_ylim(lo-.1*gap,hi+.35*gap)
fig.suptitle('Arithmetic-only instruction: fixed versus freshly generated A',x=.085,y=.98,ha='left',fontsize=18,fontweight='bold')
fig.text(.085,.924,'Each run: 50 questions × 10 trials × 3 checkpoints = 1,500 evaluations. Same corrections and B instruction.',fontsize=10,color='#526177')
fig.text(.085,.09,'Within each checkpoint, all windows use the same complete-50 responses. Fixed A: 468/500/500; fresh A: 464/500/500.',fontsize=8.5,color='#526177')
fig.text(.085,.055,'Shading: pointwise 95% question-bootstrap intervals. Matching y-axis scales within each row; equal question weights.',fontsize=8.5,color='#526177')
fig.text(.085,.02,'The full window averages the two halves. Scores are entropy-ablation proxies; no answer-correctness evaluation.',fontsize=8.5,color='#526177')
fig.subplots_adjust(left=.11,right=.98,top=.85,bottom=.16,hspace=.24,wspace=.14)
fig.savefig(out/'fixed_vs_fresh_a_windows.png',dpi=210,facecolor='white');fig.savefig(out/'fixed_vs_fresh_a_windows.svg',facecolor='white')
for name,key in [('window_means','means'),('checkpoint_tests','comparisons')]:
 with (out/(name+'.csv')).open('w',newline='') as f:
  w=csv.DictWriter(f,fieldnames=list(data[1][key][0]));w.writeheader();w.writerows(data[1][key])
